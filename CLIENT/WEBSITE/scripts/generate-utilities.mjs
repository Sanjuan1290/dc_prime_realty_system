import {spawnSync} from 'node:child_process';
import {mkdtempSync,readFileSync,writeFileSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import postcss from 'postcss';

// Scope each selector once. Nested selectors inherit their parent's scope;
// prefixing them again adds unnecessary specificity to interaction states.
export function scopeUtilities(css){
  const ast=postcss.parse(css);
  ast.walkRules(rule=>{
    for(let parent=rule.parent;parent;parent=parent.parent){
      if(parent.type==='rule'||(parent.type==='atrule'&&parent.name.endsWith('keyframes')))return;
    }
    rule.selectors=rule.selectors.map(selector=>selector===':root'||selector===':host'?'#root':`#root ${selector}`);
    rule.selectors=[...new Set(rule.selectors)];
  });
  return '/* Generated by npm run generate:css. Do not hand-edit. No global preflight. */\n'+ast.toString();
}

if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const website=fileURLToPath(new URL('../',import.meta.url));
  const temp=mkdtempSync(join(tmpdir(),'dc-prime-css-'));
  try{
    const output=join(temp,'utilities.css');
    const result=spawnSync(process.execPath,[resolve(website,'node_modules/@tailwindcss/cli/dist/index.mjs'),'-i','scripts/website-utilities.input.css','-o',output],{cwd:website,encoding:'utf8'});
    if(result.status!==0)throw new Error(result.stderr||result.error?.message||'CSS generation failed');
    writeFileSync(resolve(website,'src/website/styles/website-utilities.css'),scopeUtilities(readFileSync(output,'utf8')));
    console.log('Generated scoped WEBSITE utilities.');
  }finally{rmSync(temp,{recursive:true,force:true});}
}
