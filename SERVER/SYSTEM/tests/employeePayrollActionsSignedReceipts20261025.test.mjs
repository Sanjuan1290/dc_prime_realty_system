import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../../..')
const source=(p)=>readFileSync(resolve(root,p),'utf8')
const employee=source('CLIENT/SYSTEM/src/pages/System/Employees.jsx')
const actionPanel=source('CLIENT/SYSTEM/src/components/Shared/ActionPanelModal.jsx')
const salary=source('CLIENT/SYSTEM/src/pages/System/EmployeeSalary.jsx')
const detail=source('CLIENT/SYSTEM/src/components/System/employeeSalaryComponents/SalaryDetailModal.jsx')
const receipt=source('CLIENT/SYSTEM/src/components/System/employeeSalaryComponents/FundReleaseReceipt.jsx')
const controller=source('SERVER/SYSTEM/controllers/System/Employees/EmployeePayrollSignedReceipts.controller.js')
const router=source('SERVER/SYSTEM/routers/System/employeePayroll.routers.js')
const webhook=source('SERVER/SYSTEM/controllers/System/cloudinaryWebhook.controller.js')
const modal=source('CLIENT/SYSTEM/src/components/System/employeeSalaryComponents/SignedSalaryReceiptsModal.jsx')
const sql=source('SERVER/SYSTEM/migrations/20261025_employee_payroll_signed_receipts.sql')
test('Employees and Salary use action-button modals rather than an actions dropdown',()=>{
  assert.match(employee,/setActionsEmployee\(employee\)/)
  assert.match(employee,/<ActionPanelModal/); assert.match(actionPanel,/role="dialog" aria-modal="true"/)
  assert.doesNotMatch(employee,/<option value="" disabled>Other Actions/)
  assert.match(salary,/setActionsPayroll\(row\)/)
  assert.match(salary,/ariaLabel=\{`Payroll actions/)
  assert.match(salary,/Attendance Details/)
  assert.match(salary,/Final Review/)
})
test('salary labels are plain-language and original finalization date remains visible',()=>{
  assert.doesNotMatch(detail,/Immutable Official Payroll Snapshot/)
  assert.match(detail,/Finalized \{payroll.finalized_at/)
  assert.doesNotMatch(detail,/label="Overtime on Regular Holidays"/)
  assert.doesNotMatch(detail,/label="Overtime on Special Holidays"/)
  assert.match(detail,/label="Holiday Pay Rate"/)
  assert.doesNotMatch(detail,/Stored; separate holiday OT minutes are not available yet/)
})
test('printed receipt preserves original printed form headings, grid, totals and signing fields',()=>{
  for(const phrase of ['Acknowledgement Receipt for Fund Release','PAYEE','Description','# of Hours','Pay Period:','Position','Half-month Basic','Total Regular Hours Attended','Total Deduction','Total Amount:','Received by:','Witness:','Signature and Date']) assert.ok(receipt.includes(phrase),phrase)
  assert.match(receipt,/w-\[794px\]/)
  assert.match(receipt,/table-fixed border-collapse/)
  assert.match(receipt,/min-h-\[1080px\]/)
  assert.match(receipt,/min-height: 0 !important/)
  assert.doesNotMatch(receipt,/min-h-\[1123px\]/)
})
test('signed payroll upload requires released final salary and caps active receipt copies at five',()=>{
  assert.match(controller,/MAX_SIGNED_PAYROLL_FILES = 5/)
  assert.match(controller,/payroll_status !== 'released'/)
  assert.match(controller,/!record.finalized_snapshot/)
  assert.match(controller,/FOR UPDATE/)
  assert.match(controller,/COUNT\(\*\) AS total/)
  assert.match(sql,/REFERENCES employee_payrolls/)
  assert.match(sql,/UNIQUE KEY uq_employee_payroll_signed_cloudinary/)
})
test('Cloudinary folder is ID scoped, scans are mandatory and files remain private',()=>{
  assert.match(controller,/protected\/employee-payroll\/EMP-/)
  assert.match(controller,/getPerceptionPointQuotaState/)
  assert.match(controller,/verifyAuthenticatedCloudinaryAsset/)
  assert.match(controller,/context.parent_type/)
  assert.match(controller,/scan.status === 'rejected' \|\| scan.status === 'not_scanned'/)
  assert.match(controller,/file.malware_scan_status !== 'approved'/)
  assert.match(controller,/sendAuthenticatedAssetContent/)
  assert.match(webhook,/UPDATE employee_payroll_signed_receipts/)
  assert.match(sql,/cloudinary_asset_folder VARCHAR\(500\) NOT NULL/)
})
test('API protects access and upload separately and browser uses reviewed mutations',()=>{
  assert.match(router,/signed-receipts', requirePermission\(PERMISSIONS.PAYROLL_RECEIPT_PRINT\)/)
  assert.match(router,/upload-signature', requirePermission\(PERMISSIONS.PAYROLL_RELEASE\)/)
  assert.match(router,/archive', requirePermission\(PERMISSIONS.PAYROLL_RELEASE\)/)
  assert.match(modal,/confirmationHandled:\s*'compact'/)
  assert.match(modal,/appendCloudinarySecurityFields/)
  assert.match(modal,/setFiles\(result\?\.data\?\.files/)
  assert.match(modal,/Keep up to five signed copies/)
  assert.match(modal,/Open Receipt/)
  assert.match(modal,/Print/)
  assert.match(modal,/Download/)
})

